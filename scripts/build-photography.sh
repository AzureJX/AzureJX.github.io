#!/bin/bash
# Regenerates photography/web/ (resized, web-friendly JPEGs) and photography/manifest.js
# from whatever image files currently live in photography/.
#
# Run this after adding or deleting photos in photography/ so the gallery on
# index.html stays in sync. Requires macOS `sips` (built in).
set -euo pipefail
cd "$(dirname "$0")/.."

SRC="photography"
OUT="$SRC/web"
MANIFEST="$SRC/manifest.js"
MAX_DIM=1800
QUALITY=75

mkdir -p "$OUT"
rm -f "$OUT"/*.jpg

shopt -s nullglob nocaseglob
files=("$SRC"/*.jpg "$SRC"/*.jpeg "$SRC"/*.heic "$SRC"/*.png)
shopt -u nocaseglob nullglob

if [ ${#files[@]} -eq 0 ]; then
  echo "No source images found in $SRC/"
  exit 1
fi

IFS=$'\n' sorted=($(printf '%s\n' "${files[@]}" | sort -f))
unset IFS

{
  echo "// Auto-generated by scripts/build-photography.sh — do not edit by hand."
  echo "// Add or remove photos in photography/, then rerun that script to refresh this file."
  echo "const PHOTOS = ["
} > "$MANIFEST"

count=0
for f in "${sorted[@]}"; do
  base=$(basename "$f")
  name="${base%.*}"
  outfile="$OUT/$name.jpg"
  sips -Z "$MAX_DIM" -s format jpeg -s formatOptions "$QUALITY" "$f" --out "$outfile" >/dev/null 2>&1
  w=$(sips -g pixelWidth "$outfile" | awk '/pixelWidth/{print $2}')
  h=$(sips -g pixelHeight "$outfile" | awk '/pixelHeight/{print $2}')
  echo "  { file: \"web/$name.jpg\", w: $w, h: $h }," >> "$MANIFEST"
  count=$((count + 1))
done

echo "];" >> "$MANIFEST"

echo "Wrote $count images to $OUT/ and regenerated $MANIFEST"
